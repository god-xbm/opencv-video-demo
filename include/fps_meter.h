// ============================================================================
//  fps_meter.h —— 处理帧率统计
//
//  题目要求「在画面上显示处理 FPS」。看起来简单，但直接写的话会遇到三个坑：
//
//    坑 1：用"总帧数 / 总耗时"算平均 —— 前期数值严重偏低，后期几乎不动，
//          看不出卡顿，屏幕上的数字基本是摆设。
//    坑 2：用"1 / 单帧耗时"算瞬时 —— 抖动剧烈，读数在 18 和 60 之间乱跳，
//          观感很差，也说明不了真实性能。
//    坑 3：第一帧还没有任何时间差可算 —— 直接做除法会得到 0 或无穷大，
//          屏幕上闪过一个 0.0 或者 inf，很难看。
//
//  本类用「最近 N 帧滑动窗口 + 指数平滑」解决：
//    - 窗口内算平均，对单帧抖动不敏感
//    - 指数平滑抑制数值跳动，又不至于像全量平均那样迟钝
//    - 样本不足 2 个时返回 0，由显示层渲染成 "--"，不会误报 0.0
// ============================================================================
#pragma once

#include <cstddef>
#include <deque>

class FpsMeter {
public:
    // windowSize：参与平均的帧数，默认 30。
    // 30 帧在 30fps 下正好 1 秒，既是"最近一秒"的直观含义，
    // 又能平滑掉个别帧的抖动。
    explicit FpsMeter(std::size_t windowSize = 30);

    // 每处理完一帧调用一次。
    //
    // 调用位置很重要：放在 waitKey 之后，测到的是"端到端吞吐"（含显示刷新与
    // 等待），读数会稳定在源帧率附近，和肉眼看到的速度一致；
    // 放在 waitKey 之前，测到的是"纯算法吞吐"，数值可能高达几百，
    // 虽然也是真实数据，但和播放观感脱节。
    // 两种口径都说得通，本项目统一用前者，并在 README 里写明。
    void tick();

    // 当前帧率。样本不足时返回 0（显示层会渲染成 "--"）。
    double fps() const { return m_lastFps; }

private:
    std::size_t        m_window;    // 窗口大小
    std::deque<double> m_stamps;    // 最近若干帧的完成时刻（秒）
    double             m_lastFps;   // 平滑后的帧率
};
