// ============================================================================
//  overlay.h —— 画面信息叠加
//
//  这是整个作业最需要"想清楚"的一个函数，因为「保存结果」那 20 分里有一条硬要求：
//
//      输出视频中显示的帧号、分辨率和 FPS 与处理画面一致。
//
//  实现这一条最省事、也最不会出错的办法是：只写一个叠加函数，
//  只调用一次，然后把同一块内存分别交给"显示"和"写盘"。
//
//      drawOverlay(frame, info);   // 原地画，画一次
//      writer.write(frame);        // 写盘
//      cv::imshow(kWin, frame);    // 显示
//
//  因为两者消费的是同一个 cv::Mat 的同一份像素，物理上不可能不一致。
//
//  反而是一种很常见的错误写法：显示前画一次、写盘前再画一次，
//  或者两处的颜色、字号、文字格式有细微差别——只要有一处不同就扣分。
//  所以这里把"画什么、怎么画"全部收进一个函数，杜绝第二种画法存在。
// ============================================================================
#pragma once

#include <opencv2/core.hpp>

// 叠加信息：显示层需要的全部数据。
// 用一个结构体打包，好处是以后要加字段（比如时间戳、进度条）
// 不用改函数签名，调用方也不会漏传。
struct OverlayInfo {
    int      frameNumber;   // 当前帧号（从 1 开始）
    int      totalFrames;   // 总帧数，未知时为 -1
    cv::Size frameSize;     // 画面分辨率
    double   procFps;       // 处理帧率，<=0 表示样本不足（显示成 "--"）
};

// 把帧号、分辨率、处理 FPS 画到画面左上角。
//
// 采用原地修改（传引用）而不是返回一个新 Mat，原因有二：
//   1. 避免多一次整帧拷贝（1080p 一帧就是 6MB，逐帧拷贝很浪费）
//   2. 让"显示"和"写盘"天然共享同一块数据，一致性不需要额外保证
void drawOverlay(cv::Mat& canvas, const OverlayInfo& info);
